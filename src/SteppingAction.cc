SteppingAction::SteppingAction(const DetectorConstruction* detConstruction,
                               EventAction* eventAction)
  : fDetConstruction(detConstruction), fEventAction(eventAction)
{}

//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

void SteppingAction::UserSteppingAction(const G4Step* step)
{
  // Collect energy step by step

  // get volume of the current step
  auto touchable = step->GetPreStepPoint()->GetTouchableHandle();
  auto volume = touchable->GetVolume();

  // energy deposit
  auto edep = step->GetTotalEnergyDeposit();

  // the copy number of the voxel placement is the voxel index
  // can use it to index the accumulator vector - fEnergy 
  // in EventAction in this case, through the function AddVoxel()
  if (volume->GetLogicalVolume() == fDetConstruction->GetVoxelLV()) {
    fEventAction->AddVoxel(touchable->GetCopyNumber(), edep);
  }

  // To access timing information 
  // average time of step - 0.5*(post_time-pre_time)
  // GlobalTime is time since start of the event (set to 0).
  // Can in principle access LocalTime, which is time since start of the new track.
  G4double time = 0.5 * (step->GetPreStepPoint()->GetGlobalTime() + step->GetPostStepPoint()->GetGlobalTime());


//....oooOO0OOooo........oooOO0OOooo........oooOO0OOooo........oooOO0OOooo......

}  // namespace B4a
